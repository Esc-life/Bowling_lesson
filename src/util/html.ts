/**
 * HTML 문자열을 조립할 때 쓰는 도우미.
 *
 * 화면 대부분이 템플릿 문자열 + innerHTML로 그려진다. 사람이 입력한 값
 * (플레이어 이름 등)이 그 안에 그대로 들어가면 태그로 해석되므로 반드시
 * 이 함수를 거쳐야 한다. 한 곳에만 두는 이유: 복붙본이 늘어나면 그중
 * 하나가 조용히 약해지고, 그 한 군데가 곧 구멍이 된다.
 */

/** 사람이 입력한 값을 HTML 안에 넣기 전에 반드시 거친다 */
export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) =>
    c === '&' ? '&amp;' : c === '<' ? '&lt;' : c === '>' ? '&gt;' : c === '"' ? '&quot;' : '&#39;',
  );
}
